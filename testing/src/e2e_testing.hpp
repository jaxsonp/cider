#pragma once

#include <string_view>
#include <vector>
#include <filesystem>
#include <stdint.h>

#include "testing.hpp"

namespace testing::e2e
{
	constexpr std::string_view make_test_name(std::string_view file_path);

	enum class BitRequirement : uint8_t
	{
		UNSPECIFIED,
		NEEDS_32_BIT,
		NEEDS_64_BIT,
	};

	/// An e2e test fixture, embedded into the runner at build time
	class E2eTest : public Test
	{
		/// @brief Stores ciderc executable. Defaults to 'ciderc' for OS path resolution
		static std::string ciderc_executable;

		// test settings

		int expected_build_exit_code = 0;
		int expected_exit_code = 0;
		std::string expected_stdout = "";
		std::string expected_stderr = "";

		// requires
		BitRequirement bit_requirement = BitRequirement::UNSPECIFIED;

	public:
		const char *source;

		E2eTest(std::string_view file_path, const char *file_contents);

		Result run(std::filesystem::path &artifacts_dir) const override;

		/// @brief Sets the path of the ciderc executable to use for end to end testing. Throws a `std::runtime_error`
		/// if the path is invalid.
		static void set_ciderc_path(std::filesystem::path path);

		/// @brief Calls `ciderc --version` as a check that the binary is valid. Call `set_ciderc_path(...)` first
		static std::string check_ciderc_version();
	};

	// List of all e2e tests, defined by the autogenerated code
	extern const std::vector<E2eTest> e2e_tests;
}
